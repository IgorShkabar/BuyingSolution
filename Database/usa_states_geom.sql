--- US States Geometry Table (GIS Reference)
CREATE TABLE c##gis_user.usa_states_geom ( 
    state_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    state_code CHAR(2) UNIQUE NOT NULL, -- CA, TX, NY 
    state_name VARCHAR2(50) NOT NULL, 
    geom MDSYS.SDO_GEOMETRY, -- State boundary polygon or multipolygon 
    land_area_sq_mi NUMBER(10, 2) 
);
