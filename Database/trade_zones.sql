-- Table of trade zones (it depends on the specific store)
CREATE TABLE c##gis_user.trade_zones(
    zone_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id NUMBER NOT NULL,
    zone_type VARCHAR2(30), -- '10_min_drive', '3_mile_buffer'
    area_sq_miles NUMBER(10,2),
    zone_geom MDSYS.SDO_GEOMETRY, -- Polygon zone --
    
    CONSTRAINT fk_zone_store FOREIGN KEY (store_id) 
        REFERENCES c##gis_user.stores_locations(store_id) ON DELETE CASCADE
);